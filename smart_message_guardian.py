# ==========================================
# 1. DOWNLOAD DATASET & AUGMENT (INCLUDING THREATS)
# ==========================================
print("📥 Fetching dataset...")
DATA_URL = "https://archive.ics.uci.edu/static/public/228/sms+spam+collection.zip"
urllib.request.urlretrieve(DATA_URL, "sms.zip")
with zipfile.ZipFile("sms.zip", 'r') as z:
    z.extractall(".")

df = pd.read_csv("SMSSpamCollection", sep="\t", header=None, names=["label", "message"])
df["label"] = df["label"].map({"ham": 0, "spam": 1})

# Added financial scams + physical threats
modern_scams = [
    (1, "Dear customer your SBI bank account is blocked. Update your PAN card immediately at http://bit.ly/sbi-pan"),
    (1, "URGENT: Electricity power will be disconnected tonight at 9:30 PM due to unpaid bill. Call officer at 9876543210"),
    (1, "Congratulations! You have won lottery cash ₹25,00,000 in KBC. Contact manager on WhatsApp now."),
    (1, "India Post: Your package delivery failed due to incomplete address. Update here: http://bit.ly/indiapost-track"),
    (1, "Hi Mum, my phone dropped in water and is broken. This is my new temporary number. Please WhatsApp me urgently."),
    (1, "I will kill you right now. Watch your back."),
    (1, "Send the money or I will hurt your family."),
    (0, "Hi Dad, I will reach home by 8 PM today for dinner."),
    (0, "Your OTP for login is 482910. Valid for 10 minutes."),
    (0, "Amazon: Your package will be delivered today by 9 PM. Track at amazon.in/orders")
]
df_aug = pd.concat([df, pd.DataFrame(modern_scams, columns=["label", "message"])], ignore_index=True)

# ==========================================
# 2. TOKENIZE & TRAIN BI-LSTM
# ==========================================
MAX_WORDS, MAX_LEN = 6000, 100
tokenizer = Tokenizer(num_words=MAX_WORDS, oov_token="<OOV>")
tokenizer.fit_on_texts(df_aug["message"].values)

X = tokenizer.texts_to_sequences(df_aug["message"].values)
X = pad_sequences(X, maxlen=MAX_LEN, padding="post")
y = df_aug["label"].values

print("🧠 Training Bi-LSTM Model...")
model = Sequential([
    Embedding(MAX_WORDS, 64),
    Bidirectional(LSTM(32)),
    Dropout(0.3),
    Dense(16, activation="relu"),
    Dense(1, activation="sigmoid")
])
model.compile(loss="binary_crossentropy", optimizer="adam", metrics=["accuracy"])
model.fit(X, y, epochs=3, batch_size=64, verbose=0)
print("✅ Bi-LSTM ready!")

