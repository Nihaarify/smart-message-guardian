@app.route("/predict", methods=["POST"])
def predict():
    data = request.get_json(force=True)
    msg = data.get("message", "")

    # NLP Sequence prediction
    seq = tokenizer.texts_to_sequences([msg])
    padded = pad_sequences(seq, maxlen=MAX_LEN, padding="post")
    prob = float(model.predict(padded, verbose=0)[0][0])

    # Heuristics & Rules
    has_link = bool(re.search(r'(http://|https://|bit\.ly|tinyurl|\.apk)', msg, re.IGNORECASE))
    has_urgency = bool(re.search(r'(urgent|immediately|blocked|tonight|suspended|broken)', msg, re.IGNORECASE))
    has_threat = bool(re.search(r'(kill|hurt|murder|die|attack)', msg, re.IGNORECASE))

    if has_link and prob > 0.35:
        prob = min(prob + 0.20, 0.99)
    if has_urgency and prob > 0.35:
        prob = min(prob + 0.15, 0.99)

    # Instantly flag physical threats
    if has_threat:
        prob = max(prob, 0.96)

    # Thresholding
    if prob >= 0.75:
        risk = "HIGH"
        voice_alert = "Warning! Dangerous message detected. Do not click any links."
    else:
        risk = "SAFE"
        voice_alert = "Safe message received."

    return jsonify({"risk": risk, "probability": round(prob * 100, 1), "voice_alert": voice_alert})

